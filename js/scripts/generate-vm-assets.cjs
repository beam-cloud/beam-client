// Embed deterministic USTAR assets using Node built-ins, with no archive dependency.
const { readFileSync, readdirSync, writeFileSync } = require("node:fs");
const { join } = require("node:path");
const { gzipSync } = require("node:zlib");

function header(name, size, mode) {
  const block = Buffer.alloc(512);
  block.write(name, 0, 100, "utf8");
  const octal = (value, offset, width) => block.write(value.toString(8).padStart(width - 1, "0") + "\0", offset, width, "ascii");
  octal(mode, 100, 8);
  octal(0, 108, 8);
  octal(0, 116, 8);
  octal(size, 124, 12);
  octal(0, 136, 12);
  block.fill(32, 148, 156);
  block.write("0", 156, 1, "ascii");
  block.write("ustar\0", 257, 6, "ascii");
  block.write("00", 263, 2, "ascii");
  const checksum = block.reduce((sum, byte) => sum + byte, 0);
  block.write(checksum.toString(8).padStart(6, "0") + "\0 ", 148, 8, "ascii");
  return block;
}

const root = join(__dirname, "..");
const directory = join(root, "lib/resources/abstraction/vm-assets");
const chunks = [];
for (const name of readdirSync(directory).sort()) {
  const contents = readFileSync(join(directory, name));
  const mode = /\.(service|html|desktop|svg)$/.test(name) ? 0o644 : 0o755;
  chunks.push(header(name, contents.length, mode), contents, Buffer.alloc((512 - contents.length % 512) % 512));
}
chunks.push(Buffer.alloc(1024));
const payload = gzipSync(Buffer.concat(chunks)).toString("base64");
writeFileSync(join(root, "lib/resources/abstraction/vm-image-assets.ts"),
  `// Generated by scripts/generate-vm-assets.cjs from the Python-compatible VM assets.\nexport const VM_IMAGE_ASSETS = ${JSON.stringify(payload)};\n`);
